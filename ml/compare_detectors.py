"""Run 1 vs run 2 on our home photos and videos (data/home), the frames run 2 never trained on.

    .venv/Scripts/python ml/compare_detectors.py --new models/findmine12_run2.onnx

Per item: share of frames with a box of the item's own class (server threshold 0.25, frames at 2 fps).
Verdict ACCEPT only if keys improve AND no other item drops by more than 10 points. Then, before
swapping the model in, re-run ml/eval_home.py --model ... and ml/eval_cross_class.py --model ...
Writes eval/detector_compare.md.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))
sys.path.insert(0, str(ROOT / "ml"))
from eval_home import ALIASES, frames  # noqa: E402
from pipeline.detect import Detector  # noqa: E402

MAX_DROP = 0.10


def rates(model, home, fps):
    det, names = Detector(str(model)), json.loads(Path(model).with_suffix(".json").read_text())
    out = {}
    for d in sorted(p for p in Path(home).iterdir() if p.is_dir() and "__" in p.name):
        cls = ALIASES.get(d.name.split("__")[0], d.name.split("__")[0])
        if cls not in names:
            continue
        n = hit = 0
        for folder in (d / "test", d / "test" / "with_other"):
            for _, img in frames(folder, fps):
                if img is not None:
                    n += 1
                    hit += any(names[c] == cls for c, *_ in det(img))
        if n:
            out[d.name] = (hit, n)
    return out


def verdict(old, new):
    """-> (accept, reasons). keys must improve; nothing else may drop by more than MAX_DROP."""
    rate = lambda r, k: r[k][0] / r[k][1]  # noqa: E731
    keys = [k for k in old if k.startswith("keys") and k in new]
    reasons = []
    if not keys or not any(rate(new, k) > rate(old, k) for k in keys):
        reasons.append("keys did not improve")
    for k in old:
        if k in new and not k.startswith("keys") and rate(new, k) < rate(old, k) - MAX_DROP:
            reasons.append(f"{k} dropped {rate(old, k):.0%} -> {rate(new, k):.0%}")
    return not reasons, reasons


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", default=str(ROOT / "models/findmine12.onnx"))
    ap.add_argument("--new", required=True)
    ap.add_argument("--home", default=str(ROOT / "data/home"))
    ap.add_argument("--fps", type=float, default=2)
    a = ap.parse_args()
    old, new = rates(a.old, a.home, a.fps), rates(a.new, a.home, a.fps)
    lines = [f"| item | run 1 ({Path(a.old).name}) | run 2 ({Path(a.new).name}) |", "|---|---|---|"]
    for k in old:
        o, n = old[k], new.get(k, (0, 1))
        lines.append(f"| {k} | {o[0]}/{o[1]} ({o[0] / o[1]:.0%}) | {n[0]}/{n[1]} ({n[0] / n[1]:.0%}) |")
    ok, reasons = verdict(old, new)
    lines.append("\n**Verdict: " + ("ACCEPT** (next: eval_home + eval_cross_class with --model)" if ok
                                     else "KEEP RUN 1**: " + "; ".join(reasons)))
    md = "\n".join(lines)
    print(md)
    (ROOT / "eval/detector_compare.md").write_text("# Detector run 1 vs run 2 on FindMine-Home\n\n"
                                                    "Generated by `ml/compare_detectors.py`: frames with a box of the "
                                                    "item's own class (conf 0.25).\n\n" + md + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
