"""Old vs new detector on our home photos and videos (data/home), frames never used for training.

    .venv/Scripts/python ml/compare_detectors.py --new models/findmine12_run2.onnx            (run 2: keys)
    .venv/Scripts/python ml/compare_detectors.py --new models/findmine12_run3.onnx \\
        --targets wallet earbuds medicine --out eval/detector_compare_run3.md              (run 3)

Per item: share of frames with a box of the item's own class (server threshold 0.25, frames at 2 fps).
Verdict ACCEPT only if every target class has a home item that improves AND no item (keys included)
drops by more than 10 points. Then, before swapping the model in, re-run
ml/eval_home.py --model ... and ml/eval_cross_class.py --model ...
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))
sys.path.insert(0, str(ROOT / "ml"))
from eval_home import ALIASES, frames  # noqa: E402
from pipeline.detect import Detector  # noqa: E402

MAX_DROP = 0.10


def rates(model, home, fps):
    det, names = Detector(str(model)), json.loads(Path(model).with_suffix(".json").read_text())
    out = {}
    for d in sorted(p for p in Path(home).iterdir() if p.is_dir() and "__" in p.name):
        cls = ALIASES.get(d.name.split("__")[0], d.name.split("__")[0])
        if cls not in names:
            continue
        n = hit = 0
        for folder in (d / "test", d / "test" / "with_other"):
            for _, img in frames(folder, fps):
                if img is not None:
                    n += 1
                    hit += any(names[c] == cls for c, *_ in det(img))
        if n:
            out[d.name] = (hit, n)
    return out


def verdict(old, new, targets=("keys",)):
    """-> (accept, reasons). Each target class must improve on some item; no item (old targets like keys
    included) may drop by more than MAX_DROP. An item's class is its folder name before "__" (eval_home ALIASES)."""
    rate = lambda r, k: r[k][0] / r[k][1]  # noqa: E731
    cls = lambda k: ALIASES.get(k.split("__")[0], k.split("__")[0])  # noqa: E731
    reasons = []
    for t in targets:
        items = [k for k in old if cls(k) == t and k in new]
        if not items:
            reasons.append(f"no home test items for {t} (data/home/{t}__<name>/test)")
        elif not any(rate(new, k) > rate(old, k) for k in items):
            reasons.append(f"{t} did not improve")
    for k in old:
        if k in new and rate(new, k) < rate(old, k) - MAX_DROP:
            reasons.append(f"{k} dropped {rate(old, k):.0%} -> {rate(new, k):.0%}")
    return not reasons, reasons


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", default=str(ROOT / "models/findmine12.onnx"))
    ap.add_argument("--new", required=True)
    ap.add_argument("--home", default=str(ROOT / "data/home"))
    ap.add_argument("--fps", type=float, default=2)
    ap.add_argument("--targets", nargs="+", default=["keys"], help="classes the new run was trained for")
    ap.add_argument("--out", default=str(ROOT / "eval/detector_compare.md"))
    a = ap.parse_args()
    old, new = rates(a.old, a.home, a.fps), rates(a.new, a.home, a.fps)
    lines = [f"| item | old ({Path(a.old).name}) | new ({Path(a.new).name}) |", "|---|---|---|"]
    for k in old:
        o, n = old[k], new.get(k, (0, 1))
        lines.append(f"| {k} | {o[0]}/{o[1]} ({o[0] / o[1]:.0%}) | {n[0]}/{n[1]} ({n[0] / n[1]:.0%}) |")
    ok, reasons = verdict(old, new, a.targets)
    lines.append("\n**Verdict: " + ("ACCEPT** (next: eval_home + eval_cross_class with --model)" if ok
                                     else "KEEP THE OLD MODEL**: " + "; ".join(reasons)))
    md = "\n".join(lines)
    print(md)
    Path(a.out).write_text(f"# Detector {Path(a.old).name} vs {Path(a.new).name} on FindMine-Home\n\n"
                           f"Generated by `ml/compare_detectors.py --targets {' '.join(a.targets)}`: frames with a "
                           "box of the item's own class (conf 0.25).\n\n" + md + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
