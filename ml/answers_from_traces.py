"""Every "is it yours?" the app asked, the score behind it, and what the user answered: real-use labels.

    curl -s https://54-90-98-230.sslip.io/trace/export.jsonl -o eval/traces.jsonl
    .venv/Scripts/python ml/answers_from_traces.py eval/traces.jsonl [--since 2026-10-25T09:00]

In a session, the record that asked ("ask" in its actions, decision "median conf X") is paired with the next
answer record ("user: yes" / "user: no") or with a timeout ("no answer"). The user's answer is the label, so
check wrong-item rounds against eval/user_trials.csv (a blindfolded "yes" can be wrong).
Writes eval/answers_summary.md.
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pairs(records):
    """-> [(session, score, answer)] with answer "yes" | "no" | "none" (no answer before the timeout)."""
    by = defaultdict(list)
    for r in records:
        if "decision" in r:                           # state-machine records (planner records have no decision)
            by[r.get("session")].append(r)
    out = []
    for s, rs in by.items():
        pending = None
        for r in sorted(rs, key=lambda r: r.get("t", 0)):
            if "ask" in r.get("actions", []):
                m = re.search(r"median conf ([0-9.]+)", r["decision"])
                pending = float(m.group(1)) if m else None
            elif pending is not None and r["decision"].startswith("user: ") and r["decision"][6:] in ("yes", "no"):
                out.append((s, pending, r["decision"][6:]))
                pending = None
            elif pending is not None and r["decision"] == "no answer":
                out.append((s, pending, "none"))
                pending = None
    return out


def summary(ps):
    yes = [p for p in ps if p[2] == "yes"]
    no = [p for p in ps if p[2] == "no"]
    lines = [f"Asked {len(ps)} times in {len({p[0] for p in ps})} searches: {len(yes)} yes, {len(no)} no, "
             f"{len(ps) - len(yes) - len(no)} no answer.",
             f"Share of answered asks that were the user's item (yes): "
             f"{len(yes) / max(len(yes) + len(no), 1):.2f}", "",
             "| score band | yes | no | no answer |", "|---|---|---|---|"]
    for lo, hi in ((0.43, 0.48), (0.48, 0.55), (0.55, 0.62), (0.62, 1.01)):
        band = [p for p in ps if lo <= p[1] < hi]
        lines.append(f"| {lo:.2f}-{min(hi, 1):.2f} | {sum(p[2] == 'yes' for p in band)} | "
                     f"{sum(p[2] == 'no' for p in band)} | {sum(p[2] == 'none' for p in band)} |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("traces")
    ap.add_argument("--since", default="", help="only records at/after this time (ISO, e.g. 2026-10-25T09:00)")
    a = ap.parse_args()
    recs = []
    for line in open(a.traces, encoding="utf-8"):
        if line.strip():
            r = json.loads(line)
            if r.get("time", "") >= a.since:
                recs.append(r)
    md = summary(pairs(recs))
    print(md)
    (ROOT / "eval/answers_summary.md").write_text("# \"Is it yours?\" answers during use\n\nGenerated by "
                                                   "`ml/answers_from_traces.py`.\n\n" + md + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
