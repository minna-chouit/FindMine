"""Offline what-if: a stricter confidence threshold for ONE class (e.g. wallet) on the new detector, the others at
the server's 0.25. No server change: detections are computed once per model and the class's boxes below each
threshold are dropped afterwards (NMS is per class, so this equals a per-class threshold).

    .venv/Scripts/python ml/eval_class_threshold.py --new models/findmine12_run3.onnx --cls wallet \
        --thresholds 0.25 0.35 0.45 0.55 0.65 --targets earbuds

Per threshold: compare_detectors' table and verdict (plain detection, every item) and, with the server's 2x2
tile search, the class's close-ups, its room frames and false boxes of it on every other item's frames.
Writes eval/class_threshold_<cls>.md.
"""
import argparse
import json
import sys
from pathlib import Path

import cv2 as cv

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "server"), str(ROOT / "ml")]
from compare_detectors import verdict  # noqa: E402
from eval_home import ALIASES, IMG, frames  # noqa: E402
from pipeline.detect import Detector  # noqa: E402


def detections(model, items):
    """-> {item: {"plain": [dets per test frame], "tiles": [...], "refs": [dets per ref photo]}}"""
    det, out = Detector(str(model)), {}
    for d in items:
        imgs = [img for f in (d / "test", d / "test/with_other") for _, img in frames(f, 2) if img is not None]
        refs = [cv.imread(str(p)) for p in sorted((d / "ref").glob("*")) if p.suffix.lower() in IMG]
        out[d.name] = {"plain": [det(i) for i in imgs], "tiles": [det.tiles(i) for i in imgs],
                       "refs": [det(i) for i in refs]}
    return out


def strict(dets, cid, t):
    return [d for d in dets if d[0] != cid or d[1] >= t]


def measure(dets, names, cid, t):
    """-> (rates per item like compare_detectors, (close-ups, room frames, false boxes on other items) for cls)"""
    cls_of = lambda k: ALIASES.get(k.split("__")[0], k.split("__")[0])  # noqa: E731
    has = lambda ds, c: any(d[0] == c for d in strict(ds, cid, t))  # noqa: E731
    rates = {k: (sum(has(ds, names.index(cls_of(k))) for ds in v["plain"]), len(v["plain"]))
             for k, v in dets.items() if cls_of(k) in names and v["plain"]}
    mine = [k for k in dets if cls_of(k) == names[cid]]
    count = lambda ks, key: (sum(has(ds, cid) for k in ks for ds in dets[k][key]),  # noqa: E731
                             sum(len(dets[k][key]) for k in ks))
    return rates, (count(mine, "refs"), count(mine, "tiles"), count([k for k in dets if k not in mine], "tiles"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", default=str(ROOT / "models/findmine12.onnx"))
    ap.add_argument("--new", required=True)
    ap.add_argument("--cls", default="wallet")
    ap.add_argument("--thresholds", nargs="+", type=float, default=[0.25, 0.35, 0.45, 0.55, 0.65])
    ap.add_argument("--targets", nargs="+", default=["earbuds"])
    a = ap.parse_args()
    names = json.loads(Path(a.new).with_suffix(".json").read_text())
    cid = names.index(a.cls)
    items = [d for d in sorted((ROOT / "data/home").iterdir()) if d.is_dir() and "__" in d.name]
    old_rates, old_cls = measure(detections(a.old, items), names, cid, 0.25)
    new = detections(a.new, items)
    f = lambda c: f"{c[0]}/{c[1]}"  # noqa: E731
    lines = [f"| {a.cls} threshold (new model) | {a.cls} close-ups | {a.cls} room frames, tiles | false {a.cls} "
             "boxes on other items' frames, tiles | verdict (plain detection, targets " + " ".join(a.targets) + ") |",
             "|---|---|---|---|---|",
             f"| old model, 0.25 | {f(old_cls[0])} | {f(old_cls[1])} | {f(old_cls[2])} | – |"]
    for t in a.thresholds:
        rates, c = measure(new, names, cid, t)
        ok, why = verdict(old_rates, rates, a.targets)
        lines.append(f"| {t:.2f} | {f(c[0])} | {f(c[1])} | {f(c[2])} | {'ACCEPT' if ok else 'KEEP: ' + '; '.join(why)} |")
    md = "\n".join(lines)
    print(md)
    (ROOT / f"eval/class_threshold_{a.cls}.md").write_text(
        f"# {Path(a.new).name}: stricter threshold for {a.cls} only (offline)\n\nGenerated by "
        f"`ml/eval_class_threshold.py`; old = {Path(a.old).name}; every other class at 0.25.\n\n" + md + "\n",
        encoding="utf-8")


if __name__ == "__main__":
    main()
