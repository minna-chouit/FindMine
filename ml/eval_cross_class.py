"""Wrong-item risk of the any-class fallback (server/main.py ANY_CLASS_FALLBACK): when no box of the item's
class is in view, the server verifies the top MAX_VERIFY boxes of ANY class against the item's photos.
So every OTHER item's test frame (without a box of the searched item's class) is a negative here.

    .venv/Scripts/python ml/eval_cross_class.py        prints the counts; writes eval/cross_class.md
"""
import json
import sys
from pathlib import Path

import cv2 as cv

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))
sys.path.insert(0, str(ROOT / "ml"))
from eval_home import ALIASES, IMG, frames, thresholds  # noqa: E402
from pipeline.detect import Detector, crop_to_item  # noqa: E402
from pipeline.verify import Verifier  # noqa: E402

MAX_VERIFY = 2  # same as server/main.py


def main(fps=2):
    model = ROOT / "models/findmine12.onnx"
    names = json.loads(model.with_suffix(".json").read_text())
    detector, verifier = Detector(str(model)), Verifier(ROOT / "models/dinov2_vits14.onnx")
    found, ask = thresholds()
    items = {}
    for d in sorted(p for p in (ROOT / "data/home").iterdir() if p.is_dir() and "__" in p.name):
        cls = ALIASES.get(d.name.split("__")[0], d.name.split("__")[0])
        if cls in names:
            refs = [verifier.features(crop_to_item(cv.imread(str(p)), detector, names.index(cls)))
                    for p in sorted((d / "ref").glob("*")) if p.suffix.lower() in IMG]
            items[d.name] = {"cls": cls, "refs": refs, "dir": d}

    rows = []  # (searched item, frame's real item, frame, best fused score of the verified boxes)
    for real, it in items.items():
        for folder in (it["dir"] / "test", it["dir"] / "test" / "with_other"):
            for fname, img in frames(folder, fps):
                if img is None:
                    continue
                dets = detector(img)
                top = [d for d in sorted(dets, key=lambda d: -d[1])[:MAX_VERIFY] if min(d[4] - d[2], d[5] - d[3]) >= 8]
                feats = [verifier.features(img[int(d[3]):int(d[5]), int(d[2]):int(d[4])]) for d in top]
                for searched, s in items.items():
                    if s["cls"] == it["cls"] or not s["refs"] or not feats:
                        continue  # same class = covered by eval_home.py
                    if any(names[d[0]] == s["cls"] for d in dets):
                        continue  # a box of the searched class is in view: no fallback on this frame
                    score = max(verifier.fuse(verifier.cues(f, s["refs"])) for f in feats)
                    rows.append((searched, real, fname, score))

    n = len(rows)
    above_found = sorted((r for r in rows if r[3] >= found), key=lambda r: -r[3])
    above_ask = [r for r in rows if r[3] >= ask]
    lines = [f"Cross-class negatives (fallback frames): {n}",
             f"- at/above found {found:.2f}: {len(above_found)} ({len(above_found) / max(n, 1):.1%})",
             f"- at/above ask {ask:.2f}: {len(above_ask)} ({len(above_ask) / max(n, 1):.1%})",
             f"- highest score: {max((r[3] for r in rows), default=0):.3f}", ""]
    lines += [f"  {s} wrongly matched in a {r} frame ({f}): {sc:.3f}" for s, r, f, sc in above_found[:15]]
    md = "\n".join(lines)
    print(md)
    (ROOT / "eval/cross_class.md").write_text("# Any-class fallback: wrong-item check\n\nGenerated by "
                                              "`ml/eval_cross_class.py`.\n\n```\n" + md + "\n```\n", encoding="utf-8")


if __name__ == "__main__":
    main()
