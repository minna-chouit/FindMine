"""Summarise the blindfolded user tests: eval/user_trials.csv + eval/sus.csv -> eval/user_tests_summary.md.

    .venv/Scripts/python ml/summarize_user_tests.py
"""
import csv
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def sus_score(answers):
    """SUS (Brooke 1996): odd items score x-1, even items 5-x, sum x 2.5 -> 0..100."""
    a = [int(x) for x in answers]
    assert len(a) == 10 and all(1 <= x <= 5 for x in a), answers
    return 2.5 * sum(x - 1 if i % 2 == 0 else 5 - x for i, x in enumerate(a))


def summarize(trials, sus):
    done = [t for t in trials if t["result"]]
    groups = defaultdict(list)
    for t in done:
        groups[(t["system"], t["light"])].append(t)
    lines = ["| system | light | trials | found ≤ 2 min | median time (found) | wrong item | wrong item when look-alike present |",
             "|---|---|---|---|---|---|---|"]
    for (s, light), ts in sorted(groups.items()):
        ok = [float(t["time_s"]) for t in ts if t["result"] == "found" and t["time_s"]]
        wrong = sum(t["result"] == "wrong_item" for t in ts)
        la = [t for t in ts if t["lookalike"] == "yes"]
        la_wrong = sum(t["result"] == "wrong_item" for t in la)
        median = f"{statistics.median(ok):.0f} s" if ok else "–"
        lines.append(f"| {'A baseline' if s == 'A' else 'B FindMine'} | {light} | {len(ts)} | "
                     f"{100 * len(ok) / len(ts):.0f}% | {median} | {wrong} | {la_wrong} of {len(la)} |")
    scores = [sus_score([r[f"q{i}"] for i in range(1, 11)]) for r in sus if r["q1"]]
    lines.append(f"\n{len({t['participant'] for t in done})} volunteers, {len(done)} trials. "
                 "Plan target (N4): found within 2 min in ≥ 80% (normal) and ≥ 60% (low light/clutter) for FindMine.")
    if scores:
        lines.append(f"\nSUS for FindMine: mean {statistics.mean(scores):.1f} / 100 "
                     f"(n = {len(scores)}, range {min(scores):.0f}–{max(scores):.0f}; 68 is average).")
    quotes = [f'- "{r[k]}" ({r["participant"]})' for r in sus for k in ("helpful", "confusing") if r.get(k)]
    if quotes:
        lines += ["\nQuotes:"] + quotes
    return "\n".join(lines)


def main():
    trials = list(csv.DictReader(open(ROOT / "eval/user_trials.csv", encoding="utf-8")))
    sus = list(csv.DictReader(open(ROOT / "eval/sus.csv", encoding="utf-8")))
    md = summarize(trials, sus)
    (ROOT / "eval/user_tests_summary.md").write_text("# User tests\n\nGenerated by `ml/summarize_user_tests.py`.\n\n"
                                                     + md + "\n", encoding="utf-8")
    print(md.encode("ascii", "replace").decode())  # Windows console safe


if __name__ == "__main__":
    main()
