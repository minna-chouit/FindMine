"""Summarise the blindfolded user tests.

    eval/user_trials.csv     filled during the tests (one row per round)
    eval/form_responses.csv  the Google Form export (optional): 1-5 questions are averaged, text answers quoted

    .venv/Scripts/python ml/summarize_user_tests.py      -> eval/user_tests_summary.md
"""
import csv
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"timestamp", "horodateur", "name", "nom", "name / nom", "email address"}


def summarize(trials, form=()):
    done = [t for t in trials if t["result"]]
    groups = defaultdict(list)
    for t in done:
        groups[(t["system"], t["light"])].append(t)
    lines = ["| system | light | rounds | found ≤ 2 min | median time (found) | picked the wrong item |",
             "|---|---|---|---|---|---|"]
    for (s, light), ts in sorted(groups.items()):
        ok = [float(t["time_s"]) for t in ts if t["result"] == "found" and t["time_s"]]
        median = f"{statistics.median(ok):.0f} s" if ok else "–"
        lines.append(f"| {'A baseline' if s == 'A' else 'B FindMine'} | {light} | {len(ts)} | "
                     f"{100 * len(ok) / len(ts):.0f}% | {median} | {sum(t['result'] == 'wrong_item' for t in ts)} |")
    lines.append(f"\n{len({t['person'] for t in done})} volunteers, {len(done)} rounds. Plan target (N4): FindMine "
                 "finds the item within 2 min in ≥ 80% (normal light) and ≥ 60% (low light/clutter).")

    form = list(form)
    if form:
        cols = [c for c in form[0] if c.strip().lower() not in SKIP]
        scale = [c for c in cols if all(r[c].strip() in {"1", "2", "3", "4", "5"} for r in form if r[c].strip())
                 and any(r[c].strip() for r in form)]
        lines += ["", f"| question (1 = not at all, 5 = completely), {len(form)} answers | mean |", "|---|---|"]
        for c in scale:
            vals = [int(r[c]) for r in form if r[c].strip()]
            lines.append(f"| {c} | {statistics.mean(vals):.1f} |")
        for c in (c for c in cols if c not in scale):
            answers = [r[c].strip() for r in form if r[c].strip()]
            if answers:
                lines += ["", f"**{c}**"] + [f'- "{a}"' for a in answers]
    return "\n".join(lines)


def main():
    trials = list(csv.DictReader(open(ROOT / "eval/user_trials.csv", encoding="utf-8")))
    fp = ROOT / "eval/form_responses.csv"
    form = list(csv.DictReader(open(fp, encoding="utf-8-sig"))) if fp.exists() else []
    md = summarize(trials, form)
    (ROOT / "eval/user_tests_summary.md").write_text("# User tests\n\nGenerated by `ml/summarize_user_tests.py`.\n\n"
                                                     + md + "\n", encoding="utf-8")
    print(md.encode("ascii", "replace").decode())  # Windows console safe


if __name__ == "__main__":
    main()
